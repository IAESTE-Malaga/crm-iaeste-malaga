import { readFileSync } from 'node:fs'

const env = Object.fromEntries(
  readFileSync('.env.development.local', 'utf8').split(/\r?\n/)
    .filter((l) => l.includes('=') && !l.startsWith('#'))
    .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)])
)
